-- CarbonTrack V1 schema (shared contract A5). Enums are stored as strings.

CREATE TABLE companies (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(200) NOT NULL,
    industry      VARCHAR(100),
    baseline_year INTEGER,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id    BIGINT NOT NULL REFERENCES companies (id),
    name          VARCHAR(150) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20) NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'ANALYST'))
);
CREATE INDEX idx_users_company ON users (company_id);

CREATE TABLE facilities (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies (id),
    name       VARCHAR(150) NOT NULL,
    city       VARCHAR(100),
    state      VARCHAR(100),
    type       VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_facilities_type CHECK (type IN ('OFFICE', 'PLANT', 'WAREHOUSE', 'DATA_CENTER'))
);
CREATE INDEX idx_facilities_company ON facilities (company_id);

CREATE TABLE emission_factors (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category                VARCHAR(30) NOT NULL,
    scope                   VARCHAR(10) NOT NULL,
    unit                    VARCHAR(20) NOT NULL,
    value_kg_co2e_per_unit  NUMERIC(14, 6) NOT NULL,
    source                  VARCHAR(255),
    region                  VARCHAR(10) NOT NULL,
    year                    INTEGER NOT NULL,
    CONSTRAINT uq_emission_factors UNIQUE (category, region, year),
    CONSTRAINT ck_factors_scope CHECK (scope IN ('SCOPE_1', 'SCOPE_2', 'SCOPE_3'))
);

CREATE TABLE activity_records (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id  BIGINT NOT NULL REFERENCES companies (id),
    facility_id BIGINT NOT NULL REFERENCES facilities (id),
    category    VARCHAR(30) NOT NULL,
    scope       VARCHAR(10) NOT NULL,
    quantity    NUMERIC(16, 3) NOT NULL,
    unit        VARCHAR(20) NOT NULL,
    year        INTEGER NOT NULL,
    month       INTEGER NOT NULL,
    factor_id   BIGINT NOT NULL REFERENCES emission_factors (id),
    co2e_kg     NUMERIC(18, 3) NOT NULL,
    source      VARCHAR(10) NOT NULL,
    created_by  BIGINT REFERENCES users (id),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_activity_month CHECK (month BETWEEN 1 AND 12),
    CONSTRAINT ck_activity_scope CHECK (scope IN ('SCOPE_1', 'SCOPE_2', 'SCOPE_3')),
    CONSTRAINT ck_activity_source CHECK (source IN ('MANUAL', 'CSV', 'SEED'))
);
CREATE INDEX idx_activity_company_period ON activity_records (company_id, year, month);
CREATE INDEX idx_activity_facility ON activity_records (facility_id);

CREATE TABLE targets (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id    BIGINT NOT NULL REFERENCES companies (id),
    name          VARCHAR(200) NOT NULL,
    baseline_year INTEGER NOT NULL,
    target_year   INTEGER NOT NULL,
    reduction_pct NUMERIC(5, 2) NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_targets_company ON targets (company_id);

CREATE TABLE incentive_rules (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tier              VARCHAR(10) NOT NULL UNIQUE,
    name              VARCHAR(100) NOT NULL,
    min_reduction_pct NUMERIC(5, 2) NOT NULL,
    credit_points     INTEGER NOT NULL,
    benefit           VARCHAR(500),
    CONSTRAINT ck_rules_tier CHECK (tier IN ('BRONZE', 'SILVER', 'GOLD'))
);

-- P1
CREATE TABLE reduction_actions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id        BIGINT NOT NULL REFERENCES companies (id),
    facility_id       BIGINT REFERENCES facilities (id),
    title             VARCHAR(200) NOT NULL,
    category          VARCHAR(30),
    expected_saving_kg NUMERIC(18, 3),
    start_date        DATE,
    status            VARCHAR(15) NOT NULL,
    CONSTRAINT ck_actions_status CHECK (status IN ('PLANNED', 'IN_PROGRESS', 'DONE'))
);
CREATE INDEX idx_actions_company ON reduction_actions (company_id);
